#!/usr/bin/env python3
"""Build Afferium's public blog, or a clearly marked draft preview."""

import argparse
from datetime import date, datetime
from html import escape
import json
import math
from pathlib import Path
import re
import shutil
from string import Template
from urllib.parse import urlparse
from zoneinfo import ZoneInfo

import markdown
import yaml

ROOT = Path(__file__).resolve().parent


def render(name, **context):
    return Template((ROOT / "layouts" / name).read_text(encoding="utf-8")).substitute(context)


def read_essay(path, today, preview=False):
    text = path.read_text(encoding="utf-8")
    match = re.fullmatch(r"---\s*\n(.*?)\n---\s*\n(.*)", text, re.DOTALL)
    if not match:
        raise ValueError(f"{path.name}: start the essay with a YAML metadata block between --- lines")
    data = yaml.safe_load(match[1])
    if not isinstance(data, dict):
        raise ValueError(f"{path.name}: metadata must contain title, date, summary, tags, and published")
    for key in ("title", "summary"):
        if not isinstance(data.get(key), str) or not data[key].strip():
            raise ValueError(f"{path.name}: {key} must contain text")
    author = data.get("author", "M.A.R.A")
    if not isinstance(author, str):
        raise ValueError(f"{path.name}: author must contain text")
    published = data.get("published", False)
    if not isinstance(published, bool):
        raise ValueError(f"{path.name}: published must be true or false, without quotes")
    try:
        essay_date = data["date"]
        if isinstance(essay_date, datetime):
            essay_date = essay_date.date()
        elif not isinstance(essay_date, date):
            essay_date = date.fromisoformat(str(essay_date))
    except (KeyError, TypeError, ValueError) as error:
        raise ValueError(f"{path.name}: date must be YYYY-MM-DD") from error
    tags = data.get("tags", [])
    if not isinstance(tags, list) or any(not isinstance(tag, str) for tag in tags):
        raise ValueError(f"{path.name}: tags must be a list, such as [Ideas, Technology]")
    slug = data.get("slug", re.sub(r"^\d{4}-\d{2}-\d{2}-", "", path.stem))
    if not isinstance(slug, str) or not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
        raise ValueError(f"{path.name}: use a lowercase, hyphenated filename or slug")
    is_draft = path.parent.name == "drafts" or not published or essay_date > today
    if is_draft and not preview:
        return None
    if not match[2].strip():
        raise ValueError(f"{path.name}: the essay body is empty")
    body = markdown.markdown(match[2], extensions=["extra", "sane_lists", "smarty", "toc"],
                             extension_configs={"footnotes": {"BACKLINK_TEXT": "↩"}})
    word_count = len(re.findall(r"\b[\w’'-]+\b", re.sub(r"<[^>]+>", " ", body)))
    return {
        "title": data["title"].strip(), "summary": data["summary"].strip(), "author": author.strip(),
        "date": essay_date, "tags": tags, "slug": slug, "body": body,
        "draft": is_draft, "minutes": max(1, math.ceil(word_count / 220)),
    }


def build(preview=False):
    config = json.loads((ROOT / "site.json").read_text(encoding="utf-8"))
    for key in ("url", "main_url"):
        parsed = urlparse(config[key])
        if parsed.scheme != "https" or not parsed.hostname or parsed.query or parsed.fragment:
            raise ValueError(f"site.json: {key} must be an HTTPS website address")
    today = datetime.now(ZoneInfo(config["timezone"])).date()
    output = ROOT / ("preview" if preview else "_site")
    if output.is_symlink():
        raise ValueError("Build output must not be a symlink")
    if output.exists():
        if any(output.iterdir()) and not (output / ".afferium-build").is_file():
            raise ValueError(f"Refusing to replace an unrecognized output directory: {output.name}")
        shutil.rmtree(output)
    output.mkdir()
    (output / ".afferium-build").write_text("Generated by build.py\n", encoding="utf-8")
    shutil.copytree(ROOT / "assets", output / "assets")
    (output / ".nojekyll").touch()

    paths = sorted((ROOT / "essays").glob("*.md"))
    if preview:
        paths += sorted((ROOT / "drafts").glob("*.md"))
    essays, slugs = [], set()
    for path in paths:
        essay = read_essay(path, today, preview)
        if essay is None:
            continue
        if essay["slug"] in slugs:
            raise ValueError(f"Duplicate essay URL: {essay['slug']}")
        slugs.add(essay["slug"])
        essays.append(essay)
    essays.sort(key=lambda essay: (essay["date"], essay["slug"]), reverse=True)

    def page(content, title, description, prefix=".", path="", body_class=""):
        canonical = config["url"].rstrip("/") + "/" + path
        head_extra = '<meta name="robots" content="noindex, nofollow">' if preview else f'<link rel="canonical" href="{escape(canonical, quote=True)}">'
        notice = ""
        if preview:
            notice = '<aside class="preview-notice"><strong>Draft preview</strong> / This is not the live blog.</aside>'
        nav = '<a class="home-button" href="' + escape(config["main_url"], quote=True) + '">Home</a>'
        if body_class == "essay-page":
            nav = f'<a href="{prefix}/index.html">Blog</a>' + nav
        return render("base.html", content=content, page_title=escape(title),
                      description=escape(description, quote=True), prefix=prefix,
                      body_class=body_class, head_extra=head_extra, main_url=escape(config["main_url"], quote=True),
                      navigation=nav, preview_notice=notice, year=today.year)

    cards = []
    for essay in essays:
        label = '<span class="draft-label">Draft preview</span>' if essay["draft"] else ""
        display_date = essay["date"].strftime("%B %d, %Y").replace(" 0", " ")
        href = f'entries/{essay["slug"]}/index.html'
        cards.append(f'''<article class="essay-card">
  <p class="card-meta"><time datetime="{essay['date'].isoformat()}">{display_date}</time><span>{essay['minutes']} min read</span>{label}</p>
  <h3><a href="{href}">{escape(essay['title'])}</a></h3>
  <p class="card-summary">{escape(essay['summary'])}</p>
  <a class="read-link" href="{href}" aria-label="Read {escape(essay['title'], quote=True)}">Read entry <span aria-hidden="true">↗</span></a>
</article>''')
        article = render("essay.html", prefix="../..", title=escape(essay["title"]),
                         summary=escape(essay["summary"]), date_iso=essay["date"].isoformat(),
                         date_display=display_date, reading_minutes=essay["minutes"],
                         tags=escape(" / ".join(essay["tags"]) or "Entry"), body=essay["body"],
                         byline=f'<span>By {escape(essay["author"])}</span><span aria-hidden="true"> / </span>' if essay["author"] else "")
        target = output / "entries" / essay["slug"]
        target.mkdir(parents=True)
        (target / "index.html").write_text(page(article, f'{essay["title"]} | Afferium', essay["summary"],
                                               prefix="../..", path=f'entries/{essay["slug"]}/', body_class="essay-page"), encoding="utf-8")
    empty = '<div class="empty-state"><h3>The first entry is on its way.</h3><p>A space for following ideas further.</p></div>'
    home = render("home.html", intro=escape(config["description"]),
                  list_label="Entries",
                  count_label=f'{len(essays)} {"entry" if len(essays) == 1 else "entries"}' if essays else "",
                  essays="\n".join(cards) if cards else empty)
    (output / "index.html").write_text(page(home, "Blog | Afferium", config["description"], body_class="blog-home"), encoding="utf-8")
    if not preview:
        (output / "CNAME").write_text(urlparse(config["url"]).hostname + "\n", encoding="utf-8")
        (output / "robots.txt").write_text("User-agent: *\nAllow: /\n", encoding="utf-8")
    else:
        (output / "robots.txt").write_text("User-agent: *\nDisallow: /\n", encoding="utf-8")
    print(f"Built {len(essays)} {'preview' if preview else 'published'} entry/entries into {output.name}/")
    return output


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--preview", action="store_true", help="Include drafts, mark previews, and disable search indexing")
    args = parser.parse_args()
    try:
        build(args.preview)
    except (ValueError, KeyError, yaml.YAMLError) as error:
        raise SystemExit(f"Build stopped: {error}") from error
